#!/usr/bin/env python3
"""Inline the lnl_syst.py spectra into viz/lnl_run_animation.html (between the
// <anim-data> and // </anim-data> markers).

    python lnl/viz/export_anim_data.py        # after lnl/sim/lnl_syst.py

Three views, each per day at 1 µA, as built and big plastics (MM 15° + TOF,
E_sum window): the opening angle for all pairs, the opening angle for |y| < 0.3,
and the reconstructed pair mass m_ee (12-19 MeV).  Also the days to 3σ with
2 % unknown structure in the IPC shape + in-run controls (the robust number).
"""
import json
import re
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / 'out' / 'syst'
HTML = HERE / 'lnl_run_animation.html'
HW = {'as built': 'asbuilt', 'big plastics': 'bigP'}


def comp(df, hw, ycat, lo=None, hi=None):
    g = df[(df.hw == hw) & (df.ycat == ycat)].sort_values('theta')
    if lo is not None:
        g = g[(g.theta > lo) & (g.theta < hi)]
    r = lambda v: [round(float(x), 4) for x in v]  # noqa: E731
    return dict(g0=r(g.g0_day + g.other_day), g1=r(g.g1_day), x17=r(g.x17_day))


def robust(lad, hw, ycat):
    r = lad[(lad.hw == hw) & (lad.ycat == ycat)]
    return dict(stat=round(float(r[r.short == 'count'].days_3sigma.iloc[0]), 2),
                robust=round(float(r[r.short == '+ in-run ctrl'].days_3sigma.iloc[0]), 2),
                shape2=round(float(r[r.short == 'struct 2 %'].days_3sigma.iloc[0]), 2))


def main():
    sp, spm = pd.read_csv(OUT / 'spectra_10d.csv'), pd.read_csv(OUT / 'spectra_10d_mass.csv')
    lad, ladm = pd.read_csv(OUT / 'ladder.csv'), pd.read_csv(OUT / 'ladder_mass.csv')
    VD, DAYS = {'theta': {}, 'ysym': {}, 'mass': {}}, {'theta': {}, 'ysym': {}, 'mass': {}}
    for hw, k in HW.items():
        VD['theta'][k], DAYS['theta'][k] = comp(sp, hw, 'all'), robust(lad, hw, 'all')
        VD['ysym'][k], DAYS['ysym'][k] = comp(sp, hw, 'y<0.3'), robust(lad, hw, 'y<0.3')
        VD['mass'][k], DAYS['mass'][k] = comp(spm, hw, 'all', 12.0, 19.0), robust(ladm, hw, 'all')
    js = ('// <anim-data> generated by lnl/viz/export_anim_data.py from lnl/out/syst (lnl_syst.py); per day at 1 µA\n'
          f'const VD = {json.dumps(VD, separators=(",", ":"))};\n'
          f'const DAYS = {json.dumps(DAYS, separators=(",", ":"))};\n'
          '// </anim-data>')
    s = HTML.read_text()
    s, n = re.subn(r'// <anim-data>.*?// </anim-data>', lambda m: js, s, flags=re.S)
    assert n == 1, 'markers not found'
    HTML.write_text(s)
    print('inlined', {k: {h: len(v['g0']) for h, v in d.items()} for k, d in VD.items()})


if __name__ == '__main__':
    main()
